/* ==========================================================================
   WHILE WE'RE HERE — book compositor.

   Reads content (markdown + json), composes physical pages, and writes:
     build/book.html     the print document (no preview chrome at all)
     build/preview.html  the same pages plus screen-only guides and navigation
     build/geometry.css  print geometry compiled from book.config.js
     prompts/image-manifest.md  regenerated from content/images.json
   ========================================================================== */

