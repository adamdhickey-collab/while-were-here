function installFonts(out) {
  const dir = path.join(out, 'fonts');
  fs.mkdirSync(dir, { recursive: true });
  let css = '/* GENERATED by scripts/build.mjs. Faces are vendored from npm. */\n';
  for (const f of FONTS) {
    const src = path.join(root, 'node_modules', f.file);
    const name = path.basename(f.file);
    if (!fs.existsSync(src)) { console.warn(`  ! missing font ${f.file}`); continue; }
    fs.copyFileSync(src, path.join(dir, name));
    css += `@font-face {
  font-family: "${f.family}";
  src: url("fonts/${name}") format("woff2");
  font-weight: ${f.weight};
  font-style: ${f.style};
  font-display: block;
}\n`;
  }
  fs.writeFileSync(path.join(out, 'fonts.css'), css);
}

/* ---- Assets -------------------------------------------------------------- */

function copyDir(from, to) {
  if (!fs.existsSync(from)) return;
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const s = path.join(from, entry.name);
    const d = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

/* ---- Build --------------------------------------------------------------- */

export function build() {
  const book = json('content/book.json');
  const toc = json('content/contents.json');
  const out = path.join(root, 'build');

  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'geometry.css'), geometryCss());
  installFonts(out);
  copyDir(path.join(root, 'src/styles'), path.join(out, 'styles'));
  copyDir(path.join(root, 'src/scripts'), path.join(out, 'scripts'));
  copyDir(path.join(root, 'public'), out);

  const { openings } = compose(book, toc);            // pass 1: find the folios
  const { pages, count } = compose(book, toc, openings); // pass 2: print them
  const body = pages.join('\n');

  fs.writeFileSync(path.join(out, 'book.html'),
    document_({ title: `${book.title} — ${book.author}`, body, preview: false }));
  fs.writeFileSync(path.join(out, 'preview.html'),
    document_({ title: `${book.title} — preview`, body, preview: true }));
  fs.writeFileSync(path.join(out, 'cover-wrap.html'), coverWrapDoc(book));
  fs.writeFileSync(path.join(out, 'direction.html'), directionDoc(book));
  fs.writeFileSync(path.join(out, 'index.html'), indexDoc(book, count));
  writeManifest();

  const sheets = Math.ceil(count / 2);
  console.log(
    `✓ ${count} interior pages (${sheets} leaves) + 2 cover surfaces` +
    `  ·  ${press ? 'PRESS: bleed + crop marks' : 'proof: trimmed, no marks'}` +
    `  ·  spine ${spineWidth()} mm (provisional)`
  );
}

build();

if (process.argv.includes('--watch')) {
  const { default: chokidar } = await import('chokidar');
  chokidar
    .watch(['content', 'src', 'public', 'book.config.js'], { cwd: root, ignoreInitial: true })
    .on('all', () => {
      try { build(); } catch (e) { console.error('✗', e.message); }
    });
  console.log('watching content/ src/ public/ …');
}
