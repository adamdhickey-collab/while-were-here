/* ---- Compositor ---------------------------------------------------------- */
/* Physical page numbering ignores the cover surfaces, as a bound book does.
   A paired spread always begins on a verso; a blank is inserted if the flow
   would land it wrong. Nothing in the layouts needs to know about this. */

function compose(book, toc, folios = {}) {
  const out = [];
  const openings = {};                        // essay title -> folio of its title page
  /* The reproduced records are one exhibit returning, and the pages say so —
     "Record 1 of 3" — with both numbers derived here, never typed, for the same
     reason the contents page derives its counts: re-pacing the book must not be
     able to leave a page lying. */
  let recordTotal = 0;
  for (const item of book.sequence) {
    if (item.type !== 'essay') continue;
    const { data } = loadDoc(item.source);
    for (const sp of data.spreads || []) if (sp.record) recordTotal += 1;
  }
  let recordN = 0;
  let n = 0;                                  // interior page counter
  let stage = 1;                              // observe → notice → understand → expand → integrate
  const nextSide = () => ((n + 1) % 2 === 1 ? 'recto' : 'verso');

  const emit = (p, { standalone = false, sideOverride = null } = {}) => {
    const side = sideOverride || nextSide();
    if (!standalone) n += 1;
    out.push(wrapPage({
      side,
      folio: p.folio && !standalone ? n : null,
      rubric: p.rubric,
      spread: p.spread,
      label: p.label,
      className: `stage-${stage} ${p.cls}`,
      body: p.html,
    }));
  };

  const emitBlankIfNeeded = (wantSide) => {
    if (nextSide() !== wantSide) {
      emit({ spread: 'blank', folio: false, cls: 'page--blank', label: 'pacing blank', html: '' });
    }
  };

  const place = (result, opts = {}) => {
    if (result.pair) emitBlankIfNeeded('verso');
    else if (opts.prefersRecto) emitBlankIfNeeded('recto');
    result.pages.forEach((p) => emit(p, opts));
  };

  for (const item of book.sequence) {
    switch (item.type) {
      case 'cover-front':
        place(L.coverFront(book, ctxBase), { standalone: true, sideOverride: 'recto' });
        break;
      case 'cover-back':
        place(L.coverBack(book, ctxBase), { standalone: true, sideOverride: 'verso' });
        break;
      case 'blank':
        place(L.blank());
        break;
      case 'handed-over':
        place(L.handedOver(item, ctxBase));
        break;
      case 'dedication':
        place(L.dedication(book));
        break;
      case 'half-title':
        place(L.halfTitle(book), { prefersRecto: true });
        break;
      case 'title-spread':
        place(L.titleSpread(book, Object.values(imagesById)));
        break;
      case 'opening-note':
        place(L.openingNote(loadDoc(item.source)), { prefersRecto: true });
        break;
      case 'contents':
        place(L.contents(book, toc, folios));
        break;
      case 'field-note': {
        const doc = loadDoc(item.source);
        if (doc.data.stage) stage = doc.data.stage;
        place(L.fieldNote({ ...doc.data, html: doc.html }, { ...ctxBase, stage }));
        break;
      }
      case 'divider': {
        const { data } = loadDoc(item.source);
        if (data.stage) stage = data.stage;
        place(L.divider(data, { ...ctxBase, stage }));
        break;
      }
      case 'essay': {
        const doc = loadDoc(item.source);
        const essay = doc.data;
        if (essay.stage) stage = essay.stage;
        const ctx = { ...ctxBase, blocks: doc.blocks, stage };
        openings[L.titleKey(essay.title)] = n + 2;   // opener is a pair: verso, then the title recto
        for (const spread of essay.spreads) {
          if (spread.record) spread.record.series = `Record ${++recordN} of ${recordTotal}`;
          const variantKey = spread.variant ? `${spread.type}-${spread.variant}` : null;
          const key = variantKey && L.essaySpreads[variantKey] ? variantKey : spread.type;
          const renderer = L.essaySpreads[key];
          if (!renderer) throw new Error(`Unknown spread type: ${key}`);
          place(renderer(spread, essay, ctx));
        }
        break;
      }
      default:
        throw new Error(`Unknown sequence item: ${item.type}`);
    }
  }

  return { pages: out, count: n, openings };
}

