async function installLicensedFonts(out) {
  const dir = path.join(out, 'fonts');
  let css = '';
  let found = 0;
  let woff2;
  try { woff2 = (await import('wawoff2')).default ?? (await import('wawoff2')); } catch { woff2 = null; }
  const cacheDir = path.join(root, 'fonts-licensed', '.ttf-cache');
  let warnedCff = false;

  for (const f of LICENSED) {
    const src = path.join(root, 'fonts-licensed', f.dir, f.file);
    if (!fs.existsSync(src)) continue;

    /* These are CFF (PostScript) outlines, and Chromium degrades a CFF face to
       Type 3 glyph procedures on the print path — prepress cannot subset those
       and some presses reject them outright. Repacking as WOFF2 does not help;
       the container is not the problem. Converting the outlines to TrueType
       does, and then it embeds as a real CID font. Verified with `pdffonts`.
       Conversion is cu2qu at 1/1000 em — the same path used to build variable
       TTFs from PostScript sources, and visually indistinguishable. */
    const ttf = path.join(cacheDir, f.file.replace(/\.otf$/i, '.ttf'));
    let name = f.file;
    if (fs.existsSync(ttf) && woff2) {
      const packed = await woff2.compress(fs.readFileSync(ttf));
      name = f.file.replace(/\.otf$/i, '.woff2');
      fs.writeFileSync(path.join(dir, name), Buffer.from(packed));
    } else {
      fs.copyFileSync(src, path.join(dir, name));
      if (!warnedCff) {
        console.warn('  ! shipping raw CFF — it will embed as Type 3 and prepress cannot subset it.');
        console.warn('    Run: npm run fonts:convert');
        warnedCff = true;
      }
    }

    css += `@font-face {
  font-family: "${f.family}";
  src: url("fonts/${name}") format("${name.endsWith('.woff2') ? 'woff2' : 'opentype'}");
  font-weight: ${f.weight};
  font-style: normal;
  font-display: block;
}\n`;
    found += 1;
  }
  return { css, found };
}

async function installFonts(out) {
  const dir = path.join(out, 'fonts');
  fs.mkdirSync(dir, { recursive: true });
  let css = '/* GENERATED by scripts/build.mjs. Faces are vendored from npm. */\n';
  for (const f of FONTS) {
    const src = path.join(root, 'node_modules', f.file);
    const name = path.basename(f.file);
    if (!fs.existsSync(src)) { console.warn(`  ! missing font ${f.file}`); continue; }
    fs.copyFileSync(src, path.join(dir, name));
    css += `@font-face {
  font-family: "${f.family}";
  src: url("fonts/${name}") format("woff2");
  font-weight: ${f.weight};
  font-style: ${f.style};
  font-display: block;
}\n`;
  }

  for (const f of CANDIDATES) {
    const src = path.join(root, 'node_modules', f.file);
    if (!fs.existsSync(src)) continue;
    const name = path.basename(f.file);
    fs.copyFileSync(src, path.join(dir, name));
    css += `@font-face {
  font-family: "${f.family}";
  src: url("fonts/${name}") format("woff2");
  font-weight: ${f.weight};
  font-style: ${f.style};
  font-display: block;
}\n`;
  }

  const licensed = await installLicensedFonts(out);
  css += licensed.css;
  /* The display voice resolves to the licensed face when it is here and to the
     open-licence one when it is not, so the book builds either way. */
  css += `\n:root { --display-family: ${licensed.found
    ? '"Falutin Title", "Fraunces", "Hoefler Text", serif'
    : '"Fraunces", "Hoefler Text", serif'}; }\n`;

  fs.writeFileSync(path.join(out, 'fonts.css'), css);
  return licensed.found;
}

/* ---- Assets -------------------------------------------------------------- */

function copyDir(from, to) {
  if (!fs.existsSync(from)) return;
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const s = path.join(from, entry.name);
    const d = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

/**
 * Copy `public/` into the build.
 *
 * A web build swaps the press masters for the committed derivatives in
 * `public/images-web` (see `npm run derive`). It must SKIP `public/images`
 * entirely rather than copy it and overwrite: on a checkout that did not fetch
 * LFS the masters are pointer files, and any master without a derivative would
 * otherwise survive into build/ as a 130-byte text file pretending to be a
 * picture. A missing image draws a labelled plate and is obvious; a pointer
 * file draws nothing and is not.
 */
function copyAssets(out) {
  const pub = path.join(root, 'public');

  /* `images-web` is never copied under its own name. It is the source for a web
     build's `images`, and in a press build it is not wanted at all — shipping it
     verbatim would put a second, redundant copy of every picture in build/. */
  for (const entry of fs.readdirSync(pub, { withFileTypes: true })) {
    if (entry.name === 'images-web') continue;
    if (entry.name === 'images' && web) continue;
    const s = path.join(pub, entry.name);
    const d = path.join(out, entry.name);
    if (entry.isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }

  if (!web) return;

  const derived = path.join(pub, 'images-web');
  if (!fs.existsSync(derived)) {
    throw new Error('BOOK_WEB=1 but public/images-web does not exist — run `npm run derive`.');
  }
  /* Replace rather than merge: a leftover master from an earlier press build
     would otherwise survive into the deployed site at full resolution. */
  fs.rmSync(path.join(out, 'images'), { recursive: true, force: true });
  copyDir(derived, path.join(out, 'images'));
}

/* ---- Build --------------------------------------------------------------- */

export async function build() {
  const book = json('content/book.json');
  const toc = json('content/contents.json');
  const out = path.join(root, 'build');

  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'geometry.css'), geometryCss());
  const licensedCount = await installFonts(out);
  copyDir(path.join(root, 'src/styles'), path.join(out, 'styles'));
  copyDir(path.join(root, 'src/scripts'), path.join(out, 'scripts'));
  copyAssets(out);

  const { openings } = compose(book, toc);            // pass 1: find the folios
  const { pages, count } = compose(book, toc, openings); // pass 2: print them
  const body = pages.join('\n');

  fs.writeFileSync(path.join(out, 'book.html'),
    document_({ title: `${book.title} — ${book.author}`, body, preview: false }));
  fs.writeFileSync(path.join(out, 'preview.html'),
    document_({ title: `${book.title} — preview`, body, preview: true }));
  fs.writeFileSync(path.join(out, 'cover-wrap.html'), coverWrapDoc(book));
  const covers = coverOptionsDoc(book);
  fs.writeFileSync(path.join(out, 'cover-options.html'), covers.screen);
  fs.writeFileSync(path.join(out, 'cover-options-print.html'), covers.print);
  fs.writeFileSync(path.join(out, 'direction.html'), directionDoc(book));
  fs.writeFileSync(path.join(out, 'type.html'), typeDoc(book));
  fs.writeFileSync(path.join(out, 'index.html'), indexDoc(book, count));
  writeManifest();

  const sheets = Math.ceil(count / 2);
  console.log(
    licensedCount
      ? `  display voice: Falutin Title (${licensedCount} weights, licensed — not in this repo)`
      : `  display voice: Fraunces (licensed faces absent; drop them in fonts-licensed/)`
  );
  console.log(
    `✓ ${count} interior pages (${sheets} leaves) + 2 cover surfaces` +
    `  ·  ${press ? 'PRESS: bleed + crop marks' : 'proof: trimmed, no marks'}` +
    `  ·  spine ${spineWidth()} mm (provisional)`
  );
}

